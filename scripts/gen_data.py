#!/usr/bin/env python3
"""gen_data.py — regenerate docs/play/data.js, the app's bundled snapshot.

It reads three files from a checkout of the Forge system and writes one JS file:

    forge/BACKLOG.md        (informational)
    forge/STATE.json        the queue state (done / doing / blocked)
    registry/deps.json      the kit graph and its consumers
    registry/repos.json     the repo fleet

Usage:
    python3 scripts/gen_data.py --src /path/to/checkout

`--src` should contain `forge/STATE.json` and `registry/{deps,repos}.json`.
The kit dependencies of each queue item are the ones the Forge pipeline assigns
(kept here so the snapshot is self-describing); everything else is read live.
"""
import argparse, datetime, json, os

# The remaining queue, with the kits each item needs (assigned by the pipeline).
QUEUE = [
    ("app-companion-forge", "Companion Forge", "app", ["web-kit"], "an offline pocket console for the Forge system"),
    ("app-aerial", "Aerial", "app", ["web-kit"], "spec pending from owner"),
    ("app-seance", "Seance", "app", ["web-kit", "crypto-kit"], "sealed notes, opened once"),
    ("app-chalk-lan", "Chalk (LAN)", "app", ["web-kit", "lan-kit"], "a shared whiteboard for the room"),
    ("app-canteen-lan", "Canteen (LAN)", "app", ["web-kit", "lan-kit"], "order from your table over the LAN"),
    ("retrofit-web-kit", "Retrofit fleet onto web-kit", "retrofit", ["web-kit"], "migrate the existing apps onto web-kit (batched)"),
]


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=".", help="checkout root containing forge/ and registry/")
    ap.add_argument("--out", default="docs/play/data.js")
    args = ap.parse_args()

    state = load(os.path.join(args.src, "forge", "STATE.json"))
    deps = load(os.path.join(args.src, "registry", "deps.json"))
    repos_json = load(os.path.join(args.src, "registry", "repos.json"))

    progress_path = os.path.join(args.src, "forge", "PROGRESS.log")
    progress = []
    if os.path.exists(progress_path):
        with open(progress_path, encoding="utf-8") as f:
            progress = f.read().strip().splitlines()[-12:]

    consumers = {c["kit"]: c["repos"] for c in deps.get("consumers", [])}
    kits = [{"id": k["id"], "type": k.get("type", "runtime"), "status": k.get("status", "unknown"),
             "repo": k.get("repo", k["id"]), "consumers": consumers.get(k["id"], [])}
            for k in deps.get("kits", [])]

    repos = [{"name": r["name"], "role": r.get("role", "-"), "score": r.get("score"),
              "private": bool(r.get("private")), "homepage": r.get("homepage") or "",
              "description": (r.get("description") or "").strip()}
             for r in repos_json.get("repos", [])]
    repos.sort(key=lambda x: (x["role"] or "", x["name"].lower()))

    data = {
        "generated": datetime.date.today().isoformat(),
        "owner": repos_json.get("owner", "drsamonline"),
        "source": "forge + registry",
        "state": {"current": state.get("current"), "done": state.get("done", []),
                  "doing": state.get("doing", []), "blocked": state.get("blocked", []),
                  "budget": state.get("budget", {"max_items_per_run": 3, "max_attempts_per_item": 3})},
        "queue": [{"id": i, "label": l, "kind": k, "deps": d, "note": n} for (i, l, k, d, n) in QUEUE],
        "kits": kits,
        "repos": repos,
        "progress": progress,
    }

    body = json.dumps(data, indent=2, ensure_ascii=False)
    js = ("/* data.js — a bundled, read-only snapshot of the Forge system.\n"
          " * Generated by scripts/gen_data.py from forge + registry. The app reads it\n"
          " * offline; it is never fetched at runtime.\n"
          " *\n"
          " * PolyForm Noncommercial License 1.0.0. (c) 2026 Dr Sohil Momin.\n"
          " */\n"
          "(function (root) {\n  \"use strict\";\n  var data = " + body + ";\n"
          "  if (typeof module !== \"undefined\" && module.exports) module.exports = data;\n"
          "  if (root) root.ForgeData = data;\n"
          "})(typeof globalThis !== \"undefined\" ? globalThis : this);\n")
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(js)
    print("wrote %s (%d bytes; queue %d, kits %d, repos %d)"
          % (args.out, len(js), len(data["queue"]), len(kits), len(repos)))


if __name__ == "__main__":
    main()
